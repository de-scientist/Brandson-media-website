function estimateReadTimeFromMarkdown(md: string) {
  const plain = md
    .replace(/```[\s\S]*?```/g, " ")
    .replace(/`[^`]*`/g, " ")
    .replace(/!\[[^\]]*\]\([^)]+\)/g, " ")
    .replace(/\[[^\]]*\]\([^)]+\)/g, " ")
    .replace(/[#>*_~\-]+/g, " ")
    .replace(/\s+/g, " ")
    .trim()

  const words = plain ? plain.split(" ").length : 0
  const minutes = Math.max(1, Math.round(words / 200))
  return { words, minutes }
}

